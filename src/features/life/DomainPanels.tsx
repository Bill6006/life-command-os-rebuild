/**
 * The blocker question, and the silence where there is not one.
 *
 * Rendered from a {@link BlockerDecision}, which never returns "nothing": it
 * either asks or says why it is not asking. The silent branch renders a line
 * rather than nothing at all, because *"the app already knows what is in the
 * way"* is a useful thing for the owner to see and an empty space is not.
 */
export function BlockerQuestion({
  decision,
  disabled,
  onAnswer,
  onLeave,
}: {
  decision: BlockerDecision
  disabled: boolean
  onAnswer: (cause: string) => void
  onLeave: () => void
}) {
  if (!decision.ask) {
    return (
      <div className="now-blocker" data-testid="blocker-silent">
        <p className="note" data-testid="blocker-silent-detail">
          {decision.detail}
        </p>
      </div>
    )
  }

  return (
    <div className="now-blocker" data-testid="blocker-question">
      <p className="domain-correction__prompt">{decision.prompt}</p>
      <p className="note">{decision.note}</p>
      <div className="domain-options">
        {decision.options.map((option) => (
          <button
            key={option.id}
            type="button"
            className="domain-option"
            disabled={disabled}
            data-testid={`blocker-${option.id}`}
            onClick={() => onAnswer(option.id)}
          >
            {option.label}
          </button>
        ))}
        <button
          type="button"
          className="domain-correction__cancel"
          disabled={disabled}
          data-testid="blocker-leave"
          onClick={onLeave}
        >
          Just leave it
        </button>
      </div>
    </div>
  )
}
