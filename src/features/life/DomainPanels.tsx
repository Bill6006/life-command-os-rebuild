/**
 * Withdrawing an entry, and moving one to the day it happened.
 *
 * Both say what they will do **before** they do it — D-165 — and both say what
 * they leave alone, which is the half that makes the gesture safe to press. The
 * third thing routing 83 found no route to, backfilling an entry that was never
 * recorded, is deliberately not here: D-165 leaves authoring a historical event
 * in the later Reach package with AUD-0050's retraction half.
 */
export function CorrectionsPanel({
  events,
  disabled,
  onWithdraw,
  onRedate,
}: {
  events: readonly CorrectableEvent[]
  disabled: boolean
  onWithdraw: (event: CorrectableEvent) => void
  onRedate: (event: CorrectableEvent, dayId: string) => void
}) {
  const [open, setOpen] = useState<string | undefined>(undefined)
  const [gesture, setGesture] = useState<CorrectionGesture>('event')
  const [day, setDay] = useState('')

  if (events.length === 0) return null

  return (
    <Panel title="Something here wrong?">
      <p className="note">
        Nothing is deleted. An entry you withdraw stays in your history, marked as withdrawn.
      </p>
      {events.map((event) => {
        const consequence = correctionConsequence(gesture, `“${event.text}”`)
        return (
          <div key={event.id} className="domain-recent__row" data-testid="correctable-event">
            <span className="domain-recent__text">{event.text}</span>
            {open === event.id ? (
              <div className="domain-correction" data-testid="correction-open">
                <div className="domain-options">
                  <button
                    type="button"
                    className="domain-option"
                    disabled={disabled}
                    data-testid="correction-gesture-event"
                    onClick={() => setGesture('event')}
                  >
                    This did not happen
                  </button>
                  <button
                    type="button"
                    className="domain-option"
                    disabled={disabled}
                    data-testid="correction-gesture-timing"
                    onClick={() => setGesture('event-timing')}
                  >
                    It was a different day
                  </button>
                </div>

                <p className="domain-correction__prompt" data-testid="correction-consequence">
                  {consequence.consequence}
                </p>
                <p className="note" data-testid="correction-preserved">
                  {consequence.preserved} {consequence.reversal}
                </p>

                {gesture === 'event-timing' ? (
                  <>
                    <label className="domain-correction__prompt" htmlFor={`redate-${event.id}`}>
                      Which day did it actually happen?
                    </label>
                    <p className="note">
                      The entry moves to that day. When you wrote it down does not change.
                    </p>
                    <input
                      id={`redate-${event.id}`}
                      type="date"
                      className="domain-input"
                      value={day === '' ? event.dayId : day}
                      disabled={disabled}
                      data-testid="correction-day"
                      onChange={(event_) => setDay(event_.target.value)}
                    />
                  </>
                ) : null}

                <div className="domain-correction__actions">
                  <button
                    type="button"
                    className="domain-option"
                    disabled={disabled}
                    data-testid="correction-apply"
                    onClick={() => {
                      if (gesture === 'event') onWithdraw(event)
                      else onRedate(event, day === '' ? event.dayId : day)
                      setOpen(undefined)
                      setDay('')
                    }}
                  >
                    Do it
                  </button>
                  <button
                    type="button"
                    className="domain-correction__cancel"
                    disabled={disabled}
                    onClick={() => setOpen(undefined)}
                  >
                    Leave it
                  </button>
                </div>
              </div>
            ) : (
              <button
                type="button"
                className="domain-linkish"
                disabled={disabled}
                aria-label={`Correct: ${event.text}`}
                data-testid="correction-open-button"
                onClick={() => {
                  setOpen(event.id)
                  setGesture('event')
                  setDay('')
                }}
              >
                Not right?
              </button>
            )}
          </div>
        )
      })}
    </Panel>
  )
}

