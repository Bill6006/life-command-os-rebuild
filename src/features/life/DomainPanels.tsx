/**
 * Where a destination may be named — the adjudication's proving scope.
 *
 * Career, Health and Money, and **not Fatherhood**: *"the growth model is the
 * product's best-evidenced mechanism, Phases 81 and 82 each corrected it, and
 * it is the hardest place to prove a new object and the worst place to break
 * one. It joins once the shape is proved."*
 *
 * The panel is absent on the other pages rather than empty. An empty one would
 * be the app inviting him to fill in something it is not ready to hold, and
 * every domain page in this product is a report before it is a form.
 */
export function DestinationPanel({
  data,
  area,
  disabled,
  onName,
  onRevise,
  onMilestone,
}: {
  data: DomainPageData
  area: string
  disabled: boolean
  onName: (draft: DestinationDraft) => void
  onRevise: (
    destination: DomainDestination,
    changes: { baseline?: string; evidence?: readonly string[]; unknowns?: readonly string[] },
  ) => void
  onMilestone: (destination: DomainDestination, statement: string) => void
}) {
  const [naming, setNaming] = useState(false)
  const [aim, setAim] = useState('')
  const [milestone, setMilestone] = useState('')
  const [filling, setFilling] = useState<string | undefined>(undefined)
  const [draft, setDraft] = useState('')

  /*
   * Three proving domains, not twelve.
   *
   * A destination already recorded is always shown — an area that gained one
   * before this rule, or through an import, must not have it silently hidden —
   * and the control that makes a new one is offered only where the object is
   * proved.
   */
  const proving = PROVING_DOMAINS.includes(data.page.domains[0]!)
  if (!proving && data.destinations.length === 0) return null

  return (
    <Panel title="What you are aiming at">
      {data.destinations.length === 0 ? (
        <p className="note" data-testid="destination-empty">
          Nothing here says what {area} is for. That is the one thing the app cannot work out on its
          own.
        </p>
      ) : null}

      {data.destinations.map((entry) => (
        <div key={entry.destination.source} className="domain-goal" data-testid="destination">
          <p className="domain-goal__statement" data-testid="destination-aim">
            {entry.reading.aim}
          </p>
          <dl className="domain-destination">
            <dt>Where you are</dt>
            <dd data-testid="destination-baseline">{entry.reading.baseline}</dd>
            <dt>Next</dt>
            <dd data-testid="destination-next">{entry.reading.next}</dd>
            {entry.reading.evidence.length === 0 ? null : (
              <>
                <dt>What would count</dt>
                <dd>
                  <ul className="domain-destination__list">
                    {entry.reading.evidence.map((line) => (
                      <li key={line}>{line}</li>
                    ))}
                  </ul>
                </dd>
              </>
            )}
            {entry.reading.unknowns.length === 0 ? null : (
              <>
                <dt>Not sure about</dt>
                <dd>
                  <ul className="domain-destination__list">
                    {entry.reading.unknowns.map((line) => (
                      <li key={line}>{line}</li>
                    ))}
                  </ul>
                </dd>
              </>
            )}
          </dl>

          {entry.destination.milestones.length === 0 ? null : (
            <ul className="domain-goal__parts" data-testid="destination-milestones">
              {entry.destination.milestones.map((milestone) => (
                <li key={milestone.goal.source} className="domain-goal__part">
                  <span className="domain-goal__part-name">{milestone.goal.statement}</span>
                  {/*
                    Three words, and they are three different facts — gate item 2.

                    "Reached" is the owner having said so on this milestone.
                    It is not a session having happened and it is not a course
                    having finished; both of those are counted separately, under
                    their own names, in the panel below.
                  */}
                  <span className="domain-goal__part-state">
                    {milestone.reached ? 'reached' : 'still ahead'}
                  </span>
                </li>
              ))}
            </ul>
          )}

          {entry.reading.missing.length === 0 ? null : (
            <p className="note" data-testid="destination-missing">
              The app does not know {entry.reading.missing.join(', ')}.
            </p>
          )}

          {filling === entry.destination.source ? (
            <div className="domain-correction">
              <label
                className="domain-correction__prompt"
                htmlFor={`destination-fill-${entry.destination.source}`}
              >
                {promptFor(entry)}
              </label>
              <p className="note">{noteFor(entry)}</p>
              <input
                id={`destination-fill-${entry.destination.source}`}
                type="text"
                className="domain-input"
                value={draft}
                disabled={disabled}
                data-testid="destination-fill-input"
                onChange={(event) => setDraft(event.target.value)}
              />
              <div className="domain-correction__actions">
                <button
                  type="button"
                  className="domain-option"
                  disabled={disabled || draft.trim() === ''}
                  data-testid="destination-fill-save"
                  onClick={() => {
                    const missing = entry.reading.missing[0]
                    if (missing === 'what the next step is') onMilestone(entry, draft)
                    else if (missing === 'where you are starting from') {
                      onRevise(entry, { baseline: draft })
                    } else if (missing === 'what would count as getting somewhere') {
                      onRevise(entry, { evidence: [draft.trim()] })
                    } else onRevise(entry, { unknowns: [draft.trim()] })
                    setFilling(undefined)
                    setDraft('')
                  }}
                >
                  Save
                </button>
                <button
                  type="button"
                  className="domain-correction__cancel"
                  disabled={disabled}
                  onClick={() => setFilling(undefined)}
                >
                  Leave it
                </button>
              </div>
            </div>
          ) : entry.reading.missing.length === 0 ? null : (
            <button
              type="button"
              className="domain-linkish"
              disabled={disabled}
              data-testid="destination-fill"
              onClick={() => {
                setFilling(entry.destination.source)
                setDraft('')
              }}
            >
              Fill that in
            </button>
          )}
        </div>
      ))}

      {!proving ? null : naming ? (
        <div className="domain-correction" data-testid="destination-form">
          <label className="domain-correction__prompt" htmlFor="destination-aim">
            What are you hoping {area} eventually looks like?
          </label>
          <p className="note">
            This is kept as what you are aiming at, in your words. It is never scored, never turned
            into a percentage, and you can change it whenever it changes.
          </p>
          <input
            id="destination-aim"
            type="text"
            className="domain-input"
            value={aim}
            disabled={disabled}
            data-testid="destination-aim-input"
            onChange={(event) => setAim(event.target.value)}
          />
          <label className="domain-correction__prompt" htmlFor="destination-milestone">
            And the next step towards it, if you know it
          </label>
          <p className="note">
            {/*
              What will happen, and only if it will — QA-84-005.

              This read `describeMilestone(milestone || 'that', …)`, so an owner
              who left the optional box empty — the ordinary case, and the one
              D-173 exists to protect — was told *"The next step in Career &
              Learning: 'that'. The app will treat this as what you are
              currently studying, and start suggesting work on it."* None of
              that happened, correctly: a blank milestone creates nothing. The
              confirmation was false precisely where the owner is least able to
              check it.
            */}
            {milestoneConfirmation(milestone, data.page.domains[0]!, area)}
          </p>
          <input
            id="destination-milestone"
            type="text"
            className="domain-input"
            value={milestone}
            disabled={disabled}
            data-testid="destination-milestone-input"
            onChange={(event) => setMilestone(event.target.value)}
          />
          <div className="domain-correction__actions">
            <button
              type="button"
              className="domain-option"
              disabled={disabled || aim.trim() === ''}
              data-testid="destination-save"
              onClick={() => {
                onName({
                  aim,
                  domain: data.page.domains[0]!,
                  ...(milestone.trim() === '' ? {} : { milestone }),
                })
                setNaming(false)
                setAim('')
                setMilestone('')
              }}
            >
              That is it
            </button>
            <button
              type="button"
              className="domain-correction__cancel"
              disabled={disabled}
              onClick={() => setNaming(false)}
            >
              Not now
            </button>
          </div>
        </div>
      ) : (
        <button
          type="button"
          className="domain-linkish"
          disabled={disabled}
          data-testid="destination-open"
          onClick={() => setNaming(true)}
        >
          Say what you are aiming at
        </button>
      )}
    </Panel>
  )
}

function promptFor(entry: DomainDestination): string {
  const missing = entry.reading.missing[0]
  if (missing === 'what the next step is') return 'What would be the next step?'
  if (missing === 'where you are starting from') return 'Where are you with this right now?'
  if (missing === 'what would count as getting somewhere') {
    return 'What would tell you this was actually happening?'
  }
  return 'What are you not sure about?'
}

function noteFor(entry: DomainDestination): string {
  const missing = entry.reading.missing[0]
  if (missing === 'what the next step is') {
    return 'This becomes a milestone with its own date, and the app will start suggesting work towards it.'
  }
  if (missing === 'where you are starting from') {
    return 'This is kept as your starting point, in your words. Nothing is measured against it.'
  }
  if (missing === 'what would count as getting somewhere') {
    return 'This is kept as what would count. The app will never decide you have got there.'
  }
  return 'This is kept as an open question, so the app stops treating it as settled.'
}

