/**
 * One create-and-confirm control for all six things — F04.
 *
 * Closed until tapped, like every other control on this page: a page that opens
 * with a form is the static questionnaire dump section 59 excludes.
 *
 * The confirmation step is not decoration. The owner reads what the app
 * understood, what it will create and **what it is not going to assume**, and
 * only then agrees. That last list is what E13 recorded him needing — typing
 * into a box with no way to tell whether the answer had been taken as a current
 * fact, a standing constraint, an aspiration or an event.
 */
export function AuthoringPanel({
  situation,
  domain,
  disabled,
  onCreate,
}: {
  situation: Situation
  domain: LifeDomainId
  disabled: boolean
  onCreate: (draft: AuthoringDraft) => void
}) {
  const [kind, setKind] = useState<AuthorableKind | undefined>(undefined)
  const [name, setName] = useState('')
  const [detail, setDetail] = useState('')
  const [dayId, setDayId] = useState('')
  const [from, setFrom] = useState('')
  const [to, setTo] = useState('')

  const on = dayFromInput(dayId)
  const startsAt = minutesFromClock(from)
  const endsAt = minutesFromClock(to)
  const draft: AuthoringDraft | undefined =
    kind === undefined
      ? undefined
      : {
          kind,
          name,
          domain,
          ...(detail.trim() === '' ? {} : { detail }),
          ...(on === undefined ? {} : { dayId: on }),
          ...(startsAt === undefined ? {} : { startsAt }),
          ...(endsAt === undefined ? {} : { endsAt }),
        }
  const proposal = draft === undefined ? undefined : proposeAuthoring(draft, situation)

  return (
    <Panel title="Tell the app about something">
      {kind === undefined ? (
        <div className="domain-options" data-testid="authoring-kinds">
          {AUTHORABLE_KINDS.map((option) => (
            <button
              key={option}
              type="button"
              className="domain-option"
              disabled={disabled}
              data-testid={`authoring-kind-${option}`}
              onClick={() => setKind(option)}
            >
              {KIND_WORD[option]}
            </button>
          ))}
        </div>
      ) : (
        <div className="domain-correction" data-testid="authoring-form">
          <label className="domain-correction__prompt" htmlFor="authoring-name">
            What do you call it?
          </label>
          <p className="note">
            The app renders what you call it, exactly. Nothing here is rephrased.
          </p>
          <input
            id="authoring-name"
            type="text"
            className="domain-input"
            value={name}
            disabled={disabled}
            data-testid="authoring-name"
            onChange={(event) => setName(event.target.value)}
          />

          {kind === 'goal' ? (
            <>
              <label className="domain-correction__prompt" htmlFor="authoring-day">
                By when, if you have a date in mind
              </label>
              <p className="note">Leave it empty and the app will not invent one.</p>
              <input
                id="authoring-day"
                type="date"
                className="domain-input"
                value={dayId}
                disabled={disabled}
                data-testid="authoring-day"
                onChange={(event) => setDayId(event.target.value)}
              />
            </>
          ) : null}

          {kind === 'obligation' ? (
            <>
              <label className="domain-correction__prompt" htmlFor="authoring-from">
                What time does it start?
              </label>
              <p className="note">
                Exact times, not rough ones — the app works around the span you give it.
              </p>
              <input
                id="authoring-from"
                type="time"
                className="domain-input"
                value={from}
                disabled={disabled}
                data-testid="authoring-from"
                onChange={(event) => setFrom(event.target.value)}
              />
              <label className="domain-correction__prompt" htmlFor="authoring-to">
                And what time does it end?
              </label>
              <p className="note">It has to end after it starts.</p>
              <input
                id="authoring-to"
                type="time"
                className="domain-input"
                value={to}
                disabled={disabled}
                data-testid="authoring-to"
                onChange={(event) => setTo(event.target.value)}
              />
              <label className="domain-correction__prompt" htmlFor="authoring-obligation-day">
                Which day?
              </label>
              <p className="note">One day for now. A weekly shape is the Day shape control.</p>
              <input
                id="authoring-obligation-day"
                type="date"
                className="domain-input"
                value={dayId}
                disabled={disabled}
                data-testid="authoring-obligation-day"
                onChange={(event) => setDayId(event.target.value)}
              />
            </>
          ) : null}

          <label className="domain-correction__prompt" htmlFor="authoring-detail">
            Anything else worth saying about it
          </label>
          <p className="note">
            Stored as you wrote it and shown back to you. The app does not read meaning into it.
          </p>
          <input
            id="authoring-detail"
            type="text"
            className="domain-input"
            value={detail}
            disabled={disabled}
            data-testid="authoring-detail"
            onChange={(event) => setDetail(event.target.value)}
          />

          {proposal === undefined ? null : (
            <div data-testid="authoring-proposal">
              <p className="domain-correction__prompt">{proposal.interpretation}</p>
              {proposal.creates.length === 0 ? null : (
                <ul className="domain-destination__list">
                  {proposal.creates.map((line) => (
                    <li key={line}>{line}</li>
                  ))}
                </ul>
              )}
              {proposal.unknowns.length === 0 ? null : (
                <p className="note" data-testid="authoring-unknowns">
                  The app will not assume {proposal.unknowns.join(', ')}.
                </p>
              )}
              {proposal.problems.map((problem) => (
                <p key={problem} className="note" data-testid="authoring-problem">
                  {problem}
                </p>
              ))}
            </div>
          )}

          <div className="domain-correction__actions">
            <button
              type="button"
              className="domain-option"
              disabled={disabled || proposal === undefined || proposal.problems.length > 0}
              data-testid="authoring-save"
              onClick={() => {
                if (draft === undefined) return
                onCreate(draft)
                setKind(undefined)
                setName('')
                setDetail('')
                setDayId('')
                setFrom('')
                setTo('')
              }}
            >
              Yes, that is it
            </button>
            <button
              type="button"
              className="domain-correction__cancel"
              disabled={disabled}
              onClick={() => setKind(undefined)}
            >
              Cancel
            </button>
          </div>
        </div>
      )}
    </Panel>
  )
}

/**
 * Something that happened with somebody — F19.
 *
 * Only appears once a person exists in this area, which is the honest
 * precondition: the control names a person from the graph rather than asking
 * for one, so it cannot exist before {@link AuthoringPanel} has been used. That
 * is also why the two sit on the same page.
 */
export function PeoplePanel({
  people,
  disabled,
  onEvent,
}: {
  people: readonly { readonly ref: EntityRef; readonly label: string }[]
  disabled: boolean
  onEvent: (person: EntityRef, nature: string) => void
}) {
  const [open, setOpen] = useState<string | undefined>(undefined)
  const [draft, setDraft] = useState('')

  if (people.length === 0) return null

  return (
    <Panel title="People here">
      {people.map((person) => (
        <div key={person.ref.id} className="domain-skill" data-testid="domain-person">
          <p className="domain-skill__name">{person.label}</p>
          {open === person.ref.id ? (
            <div className="domain-correction">
              <label className="domain-correction__prompt" htmlFor={`person-${person.ref.id}`}>
                What happened with {person.label}?
              </label>
              <p className="note">
                Stored as you wrote it, against them. It is never graded, and no meaning is read
                into it.
              </p>
              <input
                id={`person-${person.ref.id}`}
                type="text"
                className="domain-input"
                value={draft}
                disabled={disabled}
                data-testid="person-event-input"
                onChange={(event) => setDraft(event.target.value)}
              />
              <div className="domain-correction__actions">
                <button
                  type="button"
                  className="domain-option"
                  disabled={disabled || draft.trim() === ''}
                  data-testid="person-event-save"
                  onClick={() => {
                    onEvent(person.ref, draft)
                    setOpen(undefined)
                    setDraft('')
                  }}
                >
                  Save
                </button>
                <button
                  type="button"
                  className="domain-correction__cancel"
                  disabled={disabled}
                  onClick={() => setOpen(undefined)}
                >
                  Cancel
                </button>
              </div>
            </div>
          ) : (
            <button
              type="button"
              className="domain-linkish"
              disabled={disabled}
              aria-label={`Something happened with ${person.label}`}
              data-testid="person-event-open"
              onClick={() => {
                setOpen(person.ref.id)
                setDraft('')
              }}
            >
              Something happened
            </button>
          )}
        </div>
      ))}
    </Panel>
  )
}

