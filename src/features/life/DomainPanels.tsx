/**
 * One control, off by default.
 *
 * The label and the note are read from `domain/privacy.ts`, beside the policy
 * that enforces them — D-175's rule. What this promises and what
 * `createFactReader` does are one sentence in one file, so they cannot drift
 * apart the way the Private page's old promise did.
 */
export function PermissionPanel({
  granted,
  disabled,
  onSet,
}: {
  granted: boolean
  disabled: boolean
  onSet: (granted: boolean) => void
}) {
  const definition = permissionDefinition('private-influence')
  return (
    <Panel title="What the app may reason from">
      <div className="domain-veto" data-testid="permission">
        <p className="domain-veto__statement">{definition.label}</p>
        <p className="note">{definition.note}</p>
        <p className="domain-progress__says" data-testid="permission-state">
          {granted ? definition.granted : definition.withheld}
        </p>
        <button
          type="button"
          className="domain-option"
          disabled={disabled}
          aria-label={granted ? 'Stop this influencing recommendations' : definition.label}
          data-testid="permission-toggle"
          onClick={() => onSet(!granted)}
        >
          {granted
            ? 'Stop it influencing recommendations'
            : 'Allow it to influence recommendations'}
        </button>
      </div>
    </Panel>
  )
}

