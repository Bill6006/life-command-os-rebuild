/**
 * The six rungs, the courses and the milestones, as three different things.
 *
 * Gate item 2 in the shape it is written: *a completed session, a completed
 * course and a milestone are three different things on screen, and no surface
 * claims capability from attendance*. Each rung prints the sentence
 * `domain/progress.ts` generates for its own count, and beside it the thing
 * that rung is **not** evidence of — which is the half a progress display
 * usually leaves out and the half the review is about.
 */
export function ProgressPanel({
  data,
  reflection,
  disabled,
  onReflect,
}: {
  data: DomainPageData
  reflection: CourseReflection | undefined
  disabled: boolean
  onReflect: (reflection: CourseReflection, answer: OutcomeAnswer) => void
}) {
  const { progress } = data
  if (progress.rungs.length === 0 && progress.courses.length === 0 && reflection === undefined) {
    return null
  }

  return (
    <Panel title="What has actually happened">
      {progress.rungs.map((rung) => (
        <div key={rung.kind} className="domain-progress" data-testid={`progress-${rung.kind}`}>
          <p className="domain-progress__label">{rung.label}</p>
          <p className="domain-progress__says">{rung.says}</p>
          <p className="note">{rung.doesNotSay}</p>
        </div>
      ))}

      {progress.courses.length === 0 ? null : (
        <div className="domain-progress" data-testid="progress-courses">
          <p className="domain-progress__label">Courses finished</p>
          <p className="domain-progress__says">
            {progress.courses.map((course) => course.about ?? 'a course').join(', ')}
          </p>
          <p className="note">
            A course finishing is not a session finishing, and neither is getting there.
          </p>
        </div>
      )}

      {reflection === undefined ? null : (
        <div className="domain-correction" data-testid="course-reflection">
          <p className="domain-correction__prompt">{reflection.prompt}</p>
          <p className="note">{reflection.note}</p>
          <div className="domain-options">
            {reflection.answers.map((answer) => (
              <button
                key={answer.id}
                type="button"
                className="domain-option"
                disabled={disabled}
                data-testid={`course-reflection-${answer.id}`}
                onClick={() => onReflect(reflection, answer)}
              >
                {answer.label}
              </button>
            ))}
          </div>
        </div>
      )}
    </Panel>
  )
}

